def copy_directory(source: Path, destination: Path, critical: bool = False):
    """Copy a directory recursively.

    Args:
        critical: when True, a missing critical file (oh-package.json5 /
            build-profile.json5 / Index.ets) aborts with sys.exit(1) instead of
            being silently skipped — a dropped scaffold file otherwise surfaces
            only as a later compile failure.
    """
    destination.mkdir(parents=True, exist_ok=True)
    critical_names = {'oh-package.json5', 'build-profile.json5', 'Index.ets'}
    skipped = 0
    missing_critical: List[Path] = []
    for entity in source.iterdir():
        try:
            if entity.is_dir():
                copy_directory(entity, destination / entity.name, critical=critical)
            elif entity.is_file():
                shutil.copy2(entity, destination / entity.name)
        except Exception as e:
            skipped += 1
            print(f'WARN: Skipping entity during copy: {entity}, error: {e}')
            if critical and entity.name in critical_names:
                missing_critical.append(entity)
    if skipped:
        print(f'WARN: Skipped {skipped} entity/entities while copying {source}')
    if missing_critical:
        print('ERROR: Critical files missing after copy:')
        for f in missing_critical:
            print(f'  - {f}')
        sys.exit(1)


