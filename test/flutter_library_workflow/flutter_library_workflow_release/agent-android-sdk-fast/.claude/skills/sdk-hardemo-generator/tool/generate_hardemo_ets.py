@dataclass
class TestCase:
    case_id: str
    title: str
    level: str
    preconditions: str
    test_steps: List[str]  # pre-split step strings, emitted as a string[] to TestInfoPanel
    expected_result: str
    postconditions: str
    covered_apis_android: List[str] = field(default_factory=list)
    covered_apis_harmony: List[str] = field(default_factory=list)

    @property
    def class_name(self) -> str:
        return case_id_to_class_name(self.case_id)

    @property
    def file_name(self) -> str:
        return case_id_to_file_name(self.case_id)

    @property
    def page_route(self) -> str:
        return case_id_to_route(self.case_id)


@dataclass
class Module:
    id: str
    title: str
    description: str
    priority: str
    test_cases: List[TestCase] = field(default_factory=list)
    
    @property
    def class_name(self) -> str:
        return f'Module{self.id.replace("-", "")}Page'
    
    @property
    def file_name(self) -> str:
        return f'Module{self.id.replace("-", "")}Page.ets'
    
    @property
    def page_route(self) -> str:
        return f'pages/Module{self.id.replace("-", "")}Page'


def id_to_suffix(id_str: str) -> str:
    return id_str.replace('-', '')


