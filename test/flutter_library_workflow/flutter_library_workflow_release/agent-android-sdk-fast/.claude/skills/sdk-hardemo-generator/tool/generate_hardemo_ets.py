def parse_modules_from_test_cases(test_cases_data: Dict[str, Any], levels: List[str]) -> List[Module]:
    modules_data = test_cases_data.get('modules', [])
    modules: List[Module] = []
    skipped_count = 0
    
    for module_data in modules_data:
        if isinstance(module_data, dict):
            id_ = str(module_data.get('moduleCode', '') or '')
            title = str(module_data.get('moduleName', '') or '')
            description = str(module_data.get('moduleDescription', '') or '')
            priority = str(module_data.get('priority', '') or '')
            test_cases_data_list = module_data.get('test_cases') or module_data.get('testCases') or []
            
            if id_ and title:
                test_cases: List[TestCase] = []
                
                for test_case_data in test_cases_data_list:
                    if isinstance(test_case_data, dict):
                        case_id = str(test_case_data.get('id', '') or test_case_data.get('caseId', '') or '')
                        case_title = str(test_case_data.get('title', '') or '')
                        level = str(test_case_data.get('level', '') or '')
                        
                        # Apply the same level filter the checker uses (empty
                        # level is always kept). Skipped cases are counted and
                        # logged so nothing disappears silently.
                        if not should_generate(level, levels):
                            skipped_count += 1
                            continue
                        
                        if case_id and case_title:
                            preconditions = str(test_case_data.get('preconditions', '') or '')
                            expected_result = str(test_case_data.get('expected_result', '') or test_case_data.get('expected', '') or '')
                            postconditions = str(test_case_data.get('postconditions', '') or '')
                            
                            # Shared formatter returns a newline-joined string;
                            # split back into a list for string[] emission so the
                            # widget never has to parse a joined string.
                            steps_str = format_test_steps(test_case_data)
                            steps_list = [s for s in steps_str.split('\n') if s.strip()] or ['无']
                            
                            covered = parse_covered_apis(test_case_data)
                            
                            test_cases.append(TestCase(
                                case_id=case_id,
                                title=case_title,
                                level=level,
                                preconditions=preconditions,
                                test_steps=steps_list,
                                expected_result=expected_result,
                                postconditions=postconditions,
                                covered_apis_android=covered['android'],
                                covered_apis_harmony=covered['harmony'],
                            ))
                
                if test_cases:
                    modules.append(Module(
                        id=id_,
                        title=title,
                        description=description,
                        priority=priority,
                        test_cases=test_cases,
                    ))
    
    if skipped_count:
        print(f'INFO: Filtered out {skipped_count} test case(s) not in levels {levels}.')
    
    return modules


