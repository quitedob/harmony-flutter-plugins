def parse_args():
    parser = argparse.ArgumentParser(
        description='Parse test-cases JSON and generate HAR Demo ETS skeleton with TODO markers.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='''
Examples:
  python generate_hardemo_ets.py --sdk-name header-decor
  python generate_hardemo_ets.py --test-cases .ohos-adaptation/04-test-cases.json
  python generate_hardemo_ets.py --dry-run
        '''
    )
    parser.add_argument('--test-cases', default=None,
                        help='Path to test-cases JSON file (default: auto-detect 04-test-cases.json in .ohos-adaptation)')
    parser.add_argument('--scaffold', default=None,
                        help='Path to hardemo scaffold directory (default: ohos_hardemo)')
    parser.add_argument('--out', default=None,
                        help='Output demo root (default: ohos-hardemo-auto)')
    parser.add_argument('--sdk-name', default=None,
                        help='SDK name for display (default: extracted from 01-analysis.json)')
    parser.add_argument('--levels', default=','.join(DEFAULT_GENERATE_LEVELS),
                        help=f'Comma-separated case levels to generate, e.g. L0,L1 (default: {",".join(DEFAULT_GENERATE_LEVELS)}). '
                             f'Cases whose level is non-empty and not in this set are skipped (and logged).')
    parser.add_argument('--dry-run', action='store_true',
                        help='Print modules/paths; do not create or overwrite files')
    
    args = parser.parse_args()
    
    # Auto-detect 04-test-cases.json
    if args.test_cases is None:
        args.test_cases = find_test_cases_file()
    
    # Auto-detect scaffold directory
    if args.scaffold is None:
        args.scaffold = find_scaffold_directory()
    
    # Auto-detect output directory
    if args.out is None:
        args.out = 'ohos-hardemo-auto'
    
    # Auto-detect SDK name
    if args.sdk_name is None:
        args.sdk_name = read_sdk_name_from_analysis() or 'sdk-demo'
    
    return args


def find_test_cases_file() -> str:
    """Return path to test cases file (04-test-cases.json in .ohos-adaptation)."""
    original = Path('.ohos-adaptation/04-test-cases.json')
    return str(original)


def find_scaffold_directory() -> str:
    """Find scaffold directory; default to ohos_hardemo (fast flow)."""
    cwd = Path.cwd()
    # Fast flow: ohos_hardemo alongside .ohos-adaptation at SDK repo root.
    if (cwd / 'ohos_hardemo').exists():
        return 'ohos_hardemo'
    # Legacy fallback: agent-android-sdk/scaffold/hardemo in parents.
    for parent in cwd.parents:
        scaffold = parent / 'agent-android-sdk' / 'scaffold' / 'hardemo'
        if scaffold.exists():
            return str(scaffold)
    return 'ohos_hardemo'


def read_sdk_name_from_analysis() -> Optional[str]:
    """Read SDK name from 01-analysis.json (BOM-tolerant)."""
    f = Path('.ohos-adaptation/01-analysis.json')
    if not f.exists():
        return None
    try:
        data = read_json(f)
        return data.get('sdk_name', None)
    except Exception:
        return None


